/*
 * Generates src/styles/tailwind.css, the Tailwind v4 theme bridge (`npm run tokens:tailwind`).
 * verify docs-freshness fails when the committed file differs from this output.
 *
 * Reads the theme's `:root` declarations (styles/theme/*.css):
 *
 *   colours      `--color-primary: var(--primary)`, inline: the utility resolves the kit's
 *                variable at the element, so it follows `color-scheme` and any override.
 *   spacing      `--spacing-padding: var(--padding)` and the other three lengths, inline, so
 *                `p-padding` follows density the way the kit's own insets do.
 *   type steps   `--text-sm: calc(0.875rem * var(--text-scale))`, inline: the utility follows
 *                the type factor as Text does, and Tailwind emits nothing to `:root`, so the
 *                kit's own `--text-sm` is left for Text.
 *   shared names the kit's other names in a namespace Tailwind builds utilities from
 *                (`--radius-*`, `--shadow-*`, `--font-*`), restated in a plain @theme: the value
 *                Tailwind emits is the kit's own, and the utility reads the variable at the
 *                element, so a theme that moves it moves the utility too.
 *
 * Fails when a restated name has more than one declared value in the theme: restating one
 * value at `:root` would override the others.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { writeIfChanged } from './lib/write-if-changed.mjs'

const THEME_DIR = 'src/styles/theme'
const OUT = 'src/styles/tailwind.css'
const strip = (text) => text.replace(/\/\*[\s\S]*?\*\//g, '')

/** name → declared values, over the theme's `:root` blocks. */
const declared = new Map()
for (const file of readdirSync(THEME_DIR).filter((name) => name.endsWith('.css')).sort()) {
  const source = strip(readFileSync(`${THEME_DIR}/${file}`, 'utf8'))
  for (const block of source.matchAll(/(^|\n)\s*:root\s*\{([^}]*)\}/g)) {
    for (const [, name, value] of block[2].matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
      const values = declared.get(name) ?? new Set()
      values.add(value.trim().replace(/\s+/g, ' '))
      declared.set(name, values)
    }
  }
}

const failures = []
const only = (name) => {
  const values = declared.get(name)
  if (values.size > 1) {
    failures.push(`${name} has ${values.size} declared values: ${[...values].join(' | ')}`)
    return null
  }
  return [...values][0]
}

const COLOUR = /^(?:light-dark\(|oklch\(|oklab\(|color-mix\(|#|rgba?\(|hsla?\()/
const names = [...declared.keys()].sort()

const first = (name) => [...declared.get(name)][0]

const colourRows = names
  .filter((name) => !name.startsWith('--shadow') && COLOUR.test(first(name)))
  .map((name) => [`--color-${name.slice(2)}`, `var(${name})`])

const spacingRows = ['--padding', '--padding-sm', '--gap', '--gap-sm']
  .filter((name) => declared.has(name))
  .map((name) => [`--spacing-${name.slice(2)}`, `var(${name})`])

/* `--text-scale` is a factor, not a step: Tailwind would make it `text-scale`, a font size. */
const typeRows = names
  .filter((name) => name.startsWith('--text-') && name !== '--text-scale')
  .map((name) => [name, only(name)])
  .filter(([, value]) => value !== null)
  .map(([name, value]) => [name, `calc(${value} * var(--text-scale))`])

const SHARED = /^--(radius|shadow|font)(-|$)/
const sharedRows = names
  .filter((name) => SHARED.test(name))
  .map((name) => [name, only(name)])
  .filter(([, value]) => value !== null)

if (failures.length) {
  console.log(`FAIL gen:tailwind-bridge — ${failures.length} problem(s)\n`)
  for (const line of failures) console.log(`  ${line}`)
  process.exit(1)
}

const section = (title, note, rows) =>
  [`\t/* ── ${title} ${'─'.repeat(Math.max(1, 74 - title.length))}`, `\t * ${note}`, '\t */', ...rows, ''].join('\n')

const pad = (rows) => {
  const width = Math.max(...rows.map(([key]) => key.length))
  return rows.map(([key, value]) => `\t${key}:${' '.repeat(width - key.length + 1)}${value};`)
}

const file = `/*
 * themelia-ui → Tailwind CSS v4.
 *
 * GENERATED by scripts/gen-tailwind-bridge.mjs — run \`npm run tokens:tailwind\`.
 * Edit the theme, not this file. \`verify docs-freshness\` fails if the two disagree.
 *
 * Import it AFTER Tailwind and after the kit's stylesheet:
 *
 *   @import "tailwindcss";
 *   @import "themelia-ui/core.css";
 *   @import "themelia-ui/tailwind.css";
 *
 * A theme declaration only: no utilities and no rules. Tailwind drops every key no utility
 * uses.
 *
 * It makes the theme addressable from Tailwind, so \`bg-primary\`, \`text-muted-foreground\`,
 * \`rounded-sm\` and \`p-padding\` mean what they mean in the kit, and \`text-sm\` follows the type
 * factor as Text does. And it keeps Tailwind's defaults
 * off the names both declare: \`--radius-sm\`, \`--shadow-lg\`, the type steps and the font stacks
 * would otherwise take Tailwind's values. A name the kit leaves unset (\`initial\`) removes
 * Tailwind's default, so the kit's fallback holds.
 *
 * \`inline\` is load-bearing in the first block: a plain @theme resolves each key once at
 * \`:root\`, and \`bg-primary\` in a dark region would paint the light colour. The second block
 * restates literals, which must stay readable at the element so a theme can move them.
 */
@theme inline {
${[
  section('colour', "The key is Tailwind's, the value reads the kit's variable at the element.", pad(colourRows)),
  section('spacing', "The kit's four lengths, which density and scale move.", pad(spacingRows)),
  section('type', "Each step times the type factor, as Text sizes it; nothing reaches `:root`.", pad(typeRows)),
].join('\n')}}

@theme {
${section('names the kit and Tailwind both use', "The kit's own values, so Tailwind's defaults replace nothing.", pad(sharedRows))}}
`

writeIfChanged(OUT, file)
console.log(
  `tailwind bridge: ${colourRows.length} colours, ${spacingRows.length} lengths, ${typeRows.length} type steps, ${sharedRows.length} shared names → ${OUT}`,
)
