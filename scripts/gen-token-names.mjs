/**
 * Generates src/lib/ui-provider/tokens.generated.ts from the theme stylesheets
 * (styles/theme/*.css): the SemanticToken union that types the provider's `theme.colors`,
 * the ThemeVariable union of every theme variable, and THEME_DEFAULTS, each variable's
 * declared value. The ThemeTweaker reads the defaults to pair a one-mode colour edit with the
 * theme's other half. A renamed variable becomes a type error rather than an ignored override.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const THEME_DIR = 'src/styles/theme'
const OUT = 'src/lib/ui-provider/tokens.generated.ts'
const strip = (text) => text.replace(/\/\*[\s\S]*?\*\//g, '')

/* `:root` declarations only: a density preset or a colour island is not a default. */
const defaults = new Map()
for (const file of readdirSync(THEME_DIR).filter((name) => name.endsWith('.css')).sort()) {
  const source = strip(readFileSync(`${THEME_DIR}/${file}`, 'utf8'))
  for (const block of source.matchAll(/(^|\n)\s*:root\s*\{([^}]*)\}/g)) {
    for (const declaration of block[2].matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
      defaults.set(declaration[1], declaration[2].trim().replace(/\s+/g, ' '))
    }
  }
}

const COLOUR = /^(?:light-dark\(|oklch\(|oklab\(|color-mix\(|#|rgba?\(|hsla?\()/
const semantic = [...defaults]
  .filter(([name, value]) => COLOUR.test(value) && !name.startsWith('--shadow'))
  .map(([name]) => name.slice(2))
  .sort()

const union = (values) => values.map((value) => `\t| ${JSON.stringify(value)}`).join('\n')
const names = [...defaults.keys()].sort()

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-token-names.mjs — do not edit.
//
// Read from styles/theme/*.css, so the provider's typed surface and the ThemeTweaker's
// defaults cannot drift from the variables the stylesheet declares.

/** Colour variables a consumer may retheme, named without the leading \`--\`. */
export type SemanticToken =
${union(semantic)}

/** Every theme variable. */
export type ThemeVariable =
${union(names)}

/** Each theme variable's declared value; a colour is \`light-dark(light, dark)\`. */
export const THEME_DEFAULTS: Readonly<Record<ThemeVariable, string>> = {
${names.map((name) => `\t${JSON.stringify(name)}: ${JSON.stringify(defaults.get(name))},`).join('\n')}
}
`,
)

console.log(`${names.length} theme variables (${semantic.length} colours) -> ${OUT}`)
