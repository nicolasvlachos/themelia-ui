/**
 * Generates src/lib/ui-provider/tokens.generated.ts: the SemanticToken and PaletteToken
 * unions that type the provider's `theme` config, from the theme manifest and palette.css,
 * so a renamed token becomes a type error rather than an ignored override.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { theme, states } from './theme-manifest.mjs'

const strip = (name) => name.replace(/^--/, '')

/*
 * The union types `theme.colors`, so only colour-valued tokens enter: radii and border
 * widths are lengths, and the shadow ladder (ink included) is elevation, set through `vars`.
 */
const COLOUR = /^(?:var\(--|color-mix\(|oklch\(|oklab\(|#|rgba?\(|hsla?\()/
const semantic = Object.entries({ ...theme, ...states })
  .filter(([name, spec]) => !name.startsWith('--shadow') && COLOUR.test(String(spec.light)))
  .map(([name]) => strip(name))
  .sort()

const palette = [...readFileSync('src/styles/tokens/palette.css', 'utf8').matchAll(/^\t(--[a-z0-9-]+):/gim)]
  .map((m) => strip(m[1]))
  .sort()

const union = (values) => values.map((v) => `\t| ${JSON.stringify(v)}`).join('\n')

writeFileSync(
  'src/lib/ui-provider/tokens.generated.ts',
  `// GENERATED by scripts/gen-token-names.mjs — do not edit.
//
// Derived from scripts/theme-manifest.mjs and styles/tokens/palette.css, so the
// provider's typed surface cannot drift from the tokens the stylesheet actually defines.

/** Semantic tokens a consumer may retheme. Values carry meaning, not raw colour. */
export type SemanticToken =
${union(semantic)}

/** Primitive ramp steps. Overriding one moves every semantic that resolves through it. */
export type PaletteToken =
${union(palette)}
`,
)

console.log(`${semantic.length} semantic + ${palette.length} palette token names -> src/lib/ui-provider/tokens.generated.ts`)
