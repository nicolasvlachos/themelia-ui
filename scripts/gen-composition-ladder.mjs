/*
 * Writes docs/generated/composition-ladder.md: which composition rungs each feature family
 * offers, detected from its declarations, plus detail for the FOCUS families. Throws when a
 * READY_MADE component is not exported. Reads docs/generated/recipes.json.
 *   accessors    a prop named `*Accessor` or `get*`
 *   slots        a ReactNode prop named in SLOT_NAMES
 *   render props a `render*` prop typed as a function
 *   headless     an exported `use*` hook
 *   partials     more than one exported component
 *   recipe       a generated recipe attributed to the family
 */
import { readFileSync } from 'node:fs'
import { writeIfChanged } from './lib/write-if-changed.mjs'
import { publicSymbols } from './lib/public-symbols.mjs'
import { readManifest } from './lib/read-architecture-manifest.mjs'

const FOCUS = [
  'features/global-search',
  'features/filters',
  'features/comments',
  'features/data-view',
]

const READY_MADE = {
  'features/global-search': 'GlobalSearch',
  'features/filters': 'FilterLayout',
  'features/comments': 'Comments',
  'features/data-view': 'DataView',
}

const { families } = readManifest()
const recipes = JSON.parse(readFileSync('docs/generated/recipes.json', 'utf8')).recipes

const SLOT_NAMES = /^(header|footer|toolbar|empty|error|loading|aside|actions|trigger|leading|trailing|media|content|children)$/i

function audit(family) {
  const text = family.source ? readFileSync(family.source, 'utf8') : ''
  const sources = [text]
  /* Also read the barrel's local re-exports (e.g. the types file). */
  for (const match of text.matchAll(/from\s+["']\.\/([\w.-]+)["']/g)) {
    for (const ext of ['.ts', '.tsx']) {
      const path = `${family.source.replace(/\/[^/]+$/, '')}/${match[1]}${ext}`
      try {
        sources.push(readFileSync(path, 'utf8'))
      } catch {
        /* Not every specifier is a file in this family. */
      }
    }
  }
  const all = sources.join('\n')
  const symbols = publicSymbols(family.source)

  const props = [...all.matchAll(/^\s*(\w+)\??:\s*([^\n]+)$/gm)]
  const rungs = {
    accessors: props.some(([, name]) => /Accessor$|^get[A-Z]/.test(name)),
    slots: props.some(([, name, type]) => SLOT_NAMES.test(name) && /ReactNode/.test(type)),
    renderProps: props.some(([, name, type]) => /^render[A-Z]/.test(name) && /=>/.test(type)),
    headless: symbols.some((symbol) => /^use[A-Z]/.test(symbol)),
    partials: symbols.filter((symbol) => /^[A-Z]/.test(symbol)).length > 1,
    recipe: recipes.some((recipe) =>
      recipe.family === family.id || recipe.families?.includes(family.id),
    ),
  }
  return { rungs, symbols }
}

const lines = [
  '<!-- GENERATED by scripts/gen-composition-ladder.mjs — do not edit. -->',
  '',
  '# The composition ladder',
  '',
  'The [composition model](../learn/composition.md) lists eight rungs, from ordinary props to a',
  'documentation recipe. A family offers the *smallest sufficient* seam — not all eight, and',
  'not a headless hook where a prop would do.',
  '',
  'The rungs are ordinary props; controlled state and callbacks when state exists; accessors;',
  'named slots; render props; exported parts; headless hooks; and complete recipes. Passive',
  'families may stop at the first rung. Interaction features normally expose several.',
  '',
  'This table is derived from what each family declares, so it cannot describe a seam that',
  'was removed or miss one that was added. The table focuses on feature families, where the',
  'higher rungs are meaningful; the columns start at accessors.',
  '',
  '| family | accessors | slots | render props | headless hook | partials | recipe |',
  '| --- | :-: | :-: | :-: | :-: | :-: | :-: |',
]

const mark = (value) => (value ? '●' : '·')
const audited = families
  .filter((family) => family.layer === 'features' || FOCUS.includes(family.id))
  .map((family) => ({ family, ...audit(family) }))

for (const { family, rungs } of audited) {
  lines.push(
    `| \`${family.id}\` | ${mark(rungs.accessors)} | ${mark(rungs.slots)} | ` +
      `${mark(rungs.renderProps)} | ${mark(rungs.headless)} | ${mark(rungs.partials)} | ${mark(rungs.recipe)} |`,
  )
}

lines.push(
  '',
  '## The four the plan names',
  '',
  'Global Search, Filters, Comments and Data View are the demonstration cases, because a',
  'ladder that only works on a Badge proves nothing. Each is usable at three heights:',
  '',
)
for (const id of FOCUS) {
  const entry = audited.find((row) => row.family.id === id)
  if (!entry) continue
  const hooks = entry.symbols.filter((symbol) => /^use[A-Z]/.test(symbol))
  const components = entry.symbols.filter((symbol) => /^[A-Z]/.test(symbol))
  const readyMade = READY_MADE[id]
  if (!components.includes(readyMade)) {
    throw new Error(`${id} declares ${readyMade} as its ready-made entry, but does not export it`)
  }
  const parts = components.filter((component) => component !== readyMade)
  lines.push(
    `### \`${id}\``,
    '',
    `**Ready-made** — \`${readyMade}\`, dropped in with props and callbacks.`,
    '',
    parts.length
      ? `**Region-customized** — ${components.length} exported parts, so a region can be replaced ` +
        `without copying the whole: ${parts.slice(0, 5).map((c) => `\`${c}\``).join(', ')}` +
        (parts.length > 5 ? `, and ${parts.length - 5} more.` : '.')
      : '**Region-customized** — no exported parts; this family is used whole.',
    '',
    hooks.length
      ? `**Headless** — ${hooks.map((h) => `\`${h}\``).join(', ')}, for presentation the parts cannot express.`
      : '**Headless** — no hook exported; the parts are the lowest rung.',
    '',
  )
}

writeIfChanged('docs/generated/composition-ladder.md', lines.join('\n'))

const complete = audited.filter((row) => FOCUS.includes(row.family.id) && row.rungs.headless && row.rungs.partials)
console.log(
  `composition ladder: ${audited.length} feature families audited; ` +
    `${complete.length}/${FOCUS.length} demonstration families offer parts AND a headless hook`,
)
