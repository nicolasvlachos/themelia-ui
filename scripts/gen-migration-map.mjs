/*
 * Writes the migration docs under docs/generated/: migration-broad-imports.{json,md} (symbol
 * → exact subpath, derived from each family's barrel), migration.md (rendered from the
 * hand-recorded architecture/migrations.json) and migration-codemod.json (the flattened map
 * scripts/consumer/codemod.mjs reads). `verify migrations` checks the targets exist.
 */
import { readFileSync } from 'node:fs'
import { writeIfChanged } from './lib/write-if-changed.mjs'
import { starTargets } from './lib/public-symbols.mjs'
import { readManifest } from './lib/read-architecture-manifest.mjs'

const manifest = readManifest()
const pkg = JSON.parse(readFileSync('package.json', 'utf8'))

/**
 * Exported names from a barrel, values and types alike — a consumer imports both. Follows
 * `export * from "./x"`, whose file declares its exports inline rather than in a block.
 */
function symbolsOf(source) {
  const text = readFileSync(source, 'utf8')
  const names = new Set()
  for (const body of [text, ...starTargets(source, text).map((file) => readFileSync(file, 'utf8'))]) {
    for (const block of body.matchAll(/export\s*(?:type\s*)?\{([\s\S]*?)\}/g)) {
      for (const raw of block[1].split(',')) {
        const entry = raw.trim().replace(/^type\s+/, '')
        if (!entry) continue
        const name = (entry.split(/\s+as\s+/).pop() ?? entry).trim()
        if (/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) names.add(name)
      }
    }
    for (const match of body.matchAll(
      /^export\s+(?:declare\s+)?(?:async\s+)?(?:function|const|class|let|var|interface|type|enum)\s+([A-Za-z][\w]*)/gm,
    )) {
      names.add(match[1])
    }
  }
  return [...names]
}

const BROAD = ['base', 'features', 'layout', 'patterns', 'admin/patterns']

/* Where the five `blocks` domains went when it split into the general and admin profiles. */
const MOVED_SUBPATHS = {
  './blocks/timelines': './patterns/timelines',
  './blocks/analytics': './patterns/analytics',
  './blocks/onboarding': './patterns/onboarding',
  './blocks/commerce': './admin/patterns/commerce',
  './blocks/admin': './admin/patterns/access',
}
const moved = {}
const collisions = {}

for (const family of manifest.families) {
  const [layer] = family.id.split('/')
  if (!BROAD.includes(layer)) continue
  for (const symbol of symbolsOf(family.source)) {
    if (moved[symbol] && moved[symbol] !== family.export) {
      collisions[symbol] = [...new Set([...(collisions[symbol] ?? [moved[symbol]]), family.export])]
    }
    moved[symbol] ??= family.export
  }
}

const name = pkg.name
const json = {
  note: 'Generated by scripts/gen-migration-map.mjs. Phase 8 codemods read this file.',
  removedSubpaths: ['base', 'features', 'layout', 'blocks'].map((layer) => `${name}/${layer}`),
  movedSubpaths: Object.fromEntries(
    Object.entries(MOVED_SUBPATHS).map(([from, to]) => [`${name}${from.slice(1)}`, `${name}${to.slice(1)}`]),
  ),
  rootNarrowed: {
    from: `every component was re-exported from "${name}"`,
    to: 'the root carries the provider and the display primitives only — both optional-peer-free',
  },
  symbols: Object.fromEntries(
    Object.entries(moved)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([symbol, subpath]) => [symbol, `${name}${subpath.slice(1)}`]),
  ),
  ambiguous: collisions,
}
writeIfChanged('docs/generated/migration-broad-imports.json', `${JSON.stringify(json, null, 2)}\n`)

const lines = [
  '<!-- GENERATED by scripts/gen-migration-map.mjs — do not edit. -->',
  '',
  '# Migrating off the broad imports',
  '',
  `These four subpaths are no longer published, and \`${name}\` itself no longer re-exports`,
  'every component:',
  '',
  '```diff',
  ...BROAD.map((layer) => `- import { … } from "${name}/${layer}"`),
  `- import { Button } from "${name}"`,
  `+ import { Button } from "${name}/base/buttons"`,
  '```',
  '',
  'A broad barrel let one specifier pull an entire layer, and with it every optional peer',
  'inside that layer. Importing a button resolved recharts, leaflet and dnd-kit. The root is',
  'now the provider and the display primitives, both peer-free; everything else has an exact',
  'subpath.',
  '',
  '## Moved subpaths',
  '',
  '`blocks` split into a general profile and an admin one. Three of the five domains carried',
  'no business vocabulary at all — a stepper, a metric tile, a checklist — and were behind a',
  'domain door for no reason; a commerce surface could not reach `StepsBar`, so it drew its',
  'own worse stepper instead.',
  '',
  '| was | is |',
  '| --- | --- |',
  ...Object.entries(json.movedSubpaths).map(([from, to]) => `| \`${from}\` | \`${to}\` |`),
  '',
  `## Where each symbol went (${Object.keys(json.symbols).length})`,
  '',
  '| symbol | import from |',
  '| --- | --- |',
  ...Object.entries(json.symbols).map(([symbol, subpath]) => `| \`${symbol}\` | \`${subpath}\` |`),
  '',
]
if (Object.keys(collisions).length) {
  lines.push(
    '## Ambiguous names',
    '',
    'These are exported by more than one family. The subpath decides which one you get, and',
    'the broad barrel used to decide for you — silently, by layer order.',
    '',
    ...Object.entries(collisions).map(([symbol, paths]) => `- \`${symbol}\` — ${paths.map((p) => `\`${name}${p.slice(1)}\``).join(', ')}`),
    '',
  )
}
writeIfChanged('docs/generated/migration-broad-imports.md', lines.join('\n'))

/* Renames are only knowable from history, so these are hand-recorded, not derived. */
const recorded = JSON.parse(readFileSync('architecture/migrations.json', 'utf8'))

const SECTIONS = [
  ['moves', 'Moved subpaths', 'The layer above features was renamed, and the admin domains moved into the admin profile. Every one of these is a pure specifier rewrite, which is why the codemod does them for you — the stylesheet import moves with its family.'],
  ['provider', 'Provider changes', 'Behaviour, not names. `UIProvider` still exists and still behaves as it did; what changed is that the pieces it composes are now separately available, and that reaching outside the React tree is opt-in.'],
  ['props', 'Prop changes', 'One idea that had two spellings.'],
  ['css', 'CSS imports and tokens', 'One stylesheet became one per family, and the token surface lost every name that restated another. Each token table below is applied by the codemod; a name marked removed is reported, never guessed at.'],
  ['behaviour', 'Behaviour changes', 'Same name, same signature, a different answer — the kind of change a type checker cannot warn you about.'],
]

const migration = [
  '<!-- GENERATED by scripts/gen-migration-map.mjs — do not edit. -->',
  '',
  '# Migration',
  '',
  'Everything that changed for a consumer, in one place. The symbol-by-symbol table for the',
  'removed barrels is in [migration-broad-imports.md](./migration-broad-imports.md).',
  '',
  'The codemod applies every change marked mechanical below — moved subpaths, split barrel',
  'imports, renamed custom properties and renamed Tailwind utilities — and reports what it',
  'cannot decide. Run it from your project, dry first:',
  '',
  '```sh',
  `node node_modules/${name}/scripts/consumer/codemod.mjs --dry-run src/`,
  `node node_modules/${name}/scripts/consumer/codemod.mjs src/`,
  '```',
  '',
  'The rest name the edit to make and why it exists; a codemod that guesses at those would be',
  'worse than no codemod.',
  '',
]
for (const [key, title, blurb] of SECTIONS) {
  const entries = recorded[key] ?? []
  if (!entries.length) continue
  migration.push(`## ${title}`, '', blurb, '')
  for (const entry of entries) {
    migration.push(
      `### \`${entry.from}\``,
      '',
      `**Becomes** \`${entry.to}\`${entry.mechanical ? ' — mechanical, the codemod does it.' : ' — by hand.'}`,
      '',
      entry.why,
      '',
    )
    if (entry.action) migration.push(entry.action, '')
    const tokens = Object.entries(entry.tokens ?? {})
    const classes = Object.entries({ ...entry.classes, ...entry.reviewClasses })
    if (tokens.length || classes.length) {
      migration.push('| was | is |', '| --- | --- |')
      for (const [from, to] of tokens) migration.push(`| \`${from}\` | ${to ? `\`${to}\`` : 'removed — reported'} |`)
      for (const [from, to] of Object.entries(entry.classes ?? {})) migration.push(`| \`${from}\` (class) | \`${to}\` |`)
      for (const [from, note] of Object.entries(entry.reviewClasses ?? {})) migration.push(`| \`${from}\` (class) | ${note} — reported |`)
      migration.push('')
    }
  }
}
writeIfChanged('docs/generated/migration.md', migration.join('\n'))

/* The shipped codemod runs from node_modules, where architecture/ is not published. */
const pick = (key) => Object.assign({}, ...(recorded.css ?? []).map((entry) => entry[key] ?? {}))
writeIfChanged(
  'docs/generated/migration-codemod.json',
  `${JSON.stringify(
    {
      note: 'Generated by scripts/gen-migration-map.mjs from architecture/migrations.json. scripts/consumer/codemod.mjs reads it; a null token target means removed with no successor.',
      moves: Object.fromEntries((recorded.moves ?? []).filter((move) => move.mechanical).map((move) => [move.from, move.to])),
      tokens: pick('tokens'),
      classes: pick('classes'),
      reviewClasses: pick('reviewClasses'),
    },
    null,
    2,
  )}\n`,
)

const recordedCount = ['moves', 'provider', 'props', 'css', 'behaviour'].reduce(
  (n, key) => n + (recorded[key]?.length ?? 0),
  0,
)
console.log(
  `migration map: ${Object.keys(json.symbols).length} symbols across ${BROAD.length} removed subpaths, ` +
    `${recordedCount} recorded changes` +
    (Object.keys(collisions).length ? `, ${Object.keys(collisions).length} ambiguous` : ''),
)
