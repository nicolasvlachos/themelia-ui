/*
 * Writes src/preview/generated/route-layers.json (route → layer) for the sidebar badges.
 * The layer comes from each page's own `importPath` (a family can own several pages), and
 * routes.ts is parsed by regex: rows must keep the `{ path: "…", … component: X }` shape.
 * `verify docs-freshness` fails when the output is stale.
 */
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs'

/*
 * The component index's layer wins over the path segment: `typography` ships from
 * `base/typography` but is its own layer.
 */
const families = JSON.parse(readFileSync('docs/generated/component-index.json', 'utf8')).families
const layerByImport = new Map(families.filter((f) => f.import).map((f) => [f.import, f.layer]))

const PAGES = 'src/preview/pages'
const OUT = 'src/preview/generated/route-layers.json'

/* The layers a badge may show. Anything else is left unbadged. */
const LAYERS = new Set([
  'typography',
  'primitives',
  'base',
  'layout',
  'features',
  'patterns',
  'admin',
  'foundation',
])

/** page component name → the layer its `importPath` names. */
const byComponent = new Map()

for (const file of readdirSync(PAGES)) {
  if (!file.endsWith('.tsx')) continue
  const source = readFileSync(`${PAGES}/${file}`, 'utf8')

  const exported = source.match(/export function (\w+Page)\b/)
  if (!exported) continue

  const declared = source.match(/importPath=\{?["'`]([^"'`]+)["'`]/)
  if (!declared) continue

  /* Internal (`@/components/…`) and published (`themelia-ui/…`) paths name the same layer. */
  const subpath = declared[1].replace(/^@\/components\//, 'themelia-ui/')
  const declaredLayer = layerByImport.get(subpath)

  const segment = declared[1]
    .replace(/^@\/components\//, '')
    .replace(/^themelia-ui\//, '')
    .split('/')[0]

  const layer = declaredLayer ?? segment
  if (LAYERS.has(layer)) byComponent.set(exported[1], layer)
}

/* routes.ts names its component per row, which is how a path reaches a page. */
const routes = readFileSync('src/preview/routes.ts', 'utf8')
const layers = {}

for (const row of routes.matchAll(/\{\s*path:\s*"([^"]+)"[^}]*?component:\s*(\w+)/g)) {
  const layer = byComponent.get(row[2])
  if (layer) layers[row[1]] = layer
}

mkdirSync('src/preview/generated', { recursive: true })
writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      note:
        'Generated by scripts/gen-route-layers.mjs from each preview page’s own importPath. ' +
        'A route with no entry renders no badge, which is the case for the prose pages and ' +
        'anything whose page does not name an import path.',
      layers,
    },
    null,
    2,
  )}\n`,
)

console.log(`gen:route-layers — ${Object.keys(layers).length} of the route table's rows carry a layer`)
