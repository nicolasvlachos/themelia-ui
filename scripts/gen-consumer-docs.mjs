/*
 * Writes the consumer catalogue under docs/generated/ from the manifest, the barrels, the
 * built declarations, architecture/{selection,component-guidance}.json and preview pages:
 * imports.md, public-api.md, profiles.md, component-index.json (read by agents and finders),
 * recipes.json, components/*.md, plus docs/build/recipes.md. Prose should link here rather
 * than restate; `verify docs-freshness` fails stale output.
 */
import { apiExportsFor } from './lib/api-exports.mjs'
import { typesFor } from './lib/export-targets.mjs'
import { recipeFamilies, validateGuidance } from './lib/component-discovery.mjs'
import { mkdirSync, readdirSync, readFileSync, rmSync } from 'node:fs'
import { writeIfChanged } from './lib/write-if-changed.mjs'
import { readManifest } from './lib/read-architecture-manifest.mjs'
import { publicComponents, publicSymbols } from './lib/public-symbols.mjs'

/* Hand-authored judgement; verify selection keeps it in step with the manifest. */
const selection = JSON.parse(readFileSync('architecture/selection.json', 'utf8')).families

const manifest = readManifest()
const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const builtEntries = Object.entries(pkg.exports).map(([key, target]) => [key, typesFor(target)]).filter(([, file]) => file)
const builtAPI = apiExportsFor(builtEntries.map(([, file]) => file), { documentation: true })
const documentedAPI = Object.fromEntries(builtEntries.map(([key, file]) => [key, Object.fromEntries(builtAPI(file.replace(/^\.\//, '')))]))
const guidance = JSON.parse(readFileSync('architecture/component-guidance.json', 'utf8')).components
const name = pkg.name
const OUT = 'docs/generated'
mkdirSync(OUT, { recursive: true })

const HEADER = (script) => `<!-- GENERATED by scripts/${script} — do not edit. -->\n\n`
const apiSlug = (id) => id.replaceAll('/', '--')

const records = manifest.families
  .filter((family) => family.id !== 'index')
  .map((family) => {
    const symbols = publicSymbols(family.source)
    const components = publicComponents(family.source)
    return {
      id: family.id,
      profile: family.profile,
      layer: family.layer,
      entrypoint: family.export,
      import: `${name}${family.export.slice(1)}`,
      css: family.cssExport ? `${name}${family.cssExport.slice(1)}` : null,
      optionalPeers: family.optionalPeers,
      dependsOnFamilies: family.dependsOnFamilies,
      documentation: family.documentationRoute
        ? `${family.documentationRoute.label} (${family.documentationRoute.path})`
        : null,
      status: family.status,
      symbols,
      components,
      apiDoc: `components/${apiSlug(family.id)}.md`,
      ...(selection[family.id] ?? {}),
    }
  })
  .sort((a, b) => a.id.localeCompare(b.id))

const guidanceErrors = validateGuidance(guidance, records)
if (guidanceErrors.length) throw new Error(guidanceErrors.join('\n'))

/* ── imports.md ──────────────────────────────────────────────────────────────────── */
const importLines = [
  HEADER('gen-consumer-docs.mjs') + '# Exact imports',
  '',
  `Every family has one subpath. There are no layer barrels: \`${name}/base\` and its three`,
  'siblings were removed because one specifier pulled an entire layer and every optional peer',
  'inside it. The root carries the provider and the display primitives, both peer-free.',
  '',
  'Import the stylesheet column beside the exact JavaScript subpath. ESM bundlers also',
  'discover the family rules through the module graph, but the explicit form behaves the',
  'same in CJS and makes the selected CSS visible in application source.',
  '',
]
for (const profile of ['general', 'admin']) {
  const inProfile = records.filter((r) => r.profile === profile)
  importLines.push(`## ${profile} profile — ${inProfile.length} families`, '')
  importLines.push('| family | import | stylesheet | optional peers |', '| --- | --- | --- | --- |')
  for (const record of inProfile) {
    importLines.push(
      `| \`${record.id}\` | \`${record.import}\` | ${record.css ? `\`${record.css}\`` : '—'} | ${record.optionalPeers.join(', ') || '—'} |`,
    )
  }
  importLines.push('')
}

/* The inverse table: optional peer → families that reach it. */
const byPeer = new Map()
for (const record of records) {
  for (const peer of record.optionalPeers) {
    if (!byPeer.has(peer)) byPeer.set(peer, [])
    byPeer.get(peer).push(record.id)
  }
}
importLines.push(
  `## Optional peers — ${byPeer.size} of them`,
  '',
  'Each is reachable only from the families below, so a consumer who never imports one never',
  'resolves it. Release verification rejects a family that reaches an undeclared peer.',
  '',
  '| peer | reachable from |',
  '| --- | --- |',
)
for (const [peer, families] of [...byPeer].sort()) {
  importLines.push(`| \`${peer}\` | ${families.map((f) => `\`${f}\``).join(', ')} |`)
}
importLines.push('')

writeIfChanged(`${OUT}/imports.md`, importLines.join('\n'))

/* ── public-api.md ───────────────────────────────────────────────────────────────── */
const symbolRows = records.flatMap((record) =>
  record.symbols.map((symbol) => ({ symbol, record })),
)
const bySymbol = new Map()
for (const row of symbolRows) {
  if (!bySymbol.has(row.symbol)) bySymbol.set(row.symbol, [])
  bySymbol.get(row.symbol).push(row.record)
}
const apiLines = [
  HEADER('gen-consumer-docs.mjs') + '# Public API',
  '',
  `${symbolRows.length} public symbol exports (${bySymbol.size} unique names), with the exact subpath each export comes from.`,
  '',
  '| symbol | import from | documented at |',
  '| --- | --- | --- |',
  ...symbolRows
    .sort((a, b) => a.symbol.localeCompare(b.symbol) || a.record.id.localeCompare(b.record.id))
    .map(
      ({ symbol, record }) =>
        `| \`${symbol}\` | \`${record.import}\` | ` +
        `[family API](${record.apiDoc})${record.documentation ? ` · ${record.documentation}` : ''} |`,
    ),
  '',
]
writeIfChanged(`${OUT}/public-api.md`, apiLines.join('\n'))

/* ── profiles.md ─────────────────────────────────────────────────────────────────── */
const counts = (profile) => records.filter((r) => r.profile === profile).length
const profileLines = [
  HEADER('gen-consumer-docs.mjs') + '# Profiles',
  '',
  'One package, two profiles over one downward dependency graph.',
  '',
  'A profile is a **dependency ceiling**, not a subject-matter category, and not a bundle.',
  'It says which direction an import may travel; it says nothing about what a family is FOR.',
  `${counts('general')} of the ${records.length} documented families are \`general\`, and that includes the`,
  'product, order and resource workflows an admin application is mostly built from —',
  '`general` does not mean "not useful in admin software".',
  '',
  `**general** — ${counts('general')} families. Does not depend on an admin family.`,
  '',
  `**admin** — ${counts('admin')} families. Terminal: may depend on general families, and may`,
  'never be imported by one.',
  '',
  'What a consumer downloads is decided by the exact subpaths they import, not by a profile:',
  'there is no general bundle and no admin bundle. The machine-readable records —',
  '`themelia-ui/profiles/general.json` and `.../admin.json` — list every subpath',
  'available below each ceiling and the optional peers that come with it.',
  '',
  'The rule between them is enforced twice: `verify composition` fails any general family that',
  'names `src/components/admin`, and `verify architecture` fails the same edge in the manifest.',
  'A general consumer therefore cannot accidentally acquire a domain vocabulary, and an admin',
  'component cannot become a place where application policy hides.',
  '',
  '## The graph',
  '',
  '```text',
  'foundation → typography → primitives → base ─┬─ layout ────┐',
  '                                             ├─ features ──┼→ patterns → admin',
  '                                             └─────────────┘',
  '```',
  '',
  '`layout` and `features` are siblings. Neither may import `patterns`; a pattern may',
  'assemble either one. `admin` is the terminal profile layer.',
  '',
  '## Families',
  '',
  '| family | profile | layer | depends on |',
  '| --- | --- | --- | --- |',
  ...records.map(
    (r) => `| \`${r.id}\` | ${r.profile} | ${r.layer} | ${r.dependsOnFamilies.length || '—'} |`,
  ),
  '',
]
writeIfChanged(`${OUT}/profiles.md`, profileLines.join('\n'))

/* ── recipes.json ────────────────────────────────────────────────────────────────── */
/*
 * Recipes are the preview pages' own `<Example code={…}>` blocks, attributed by the public
 * symbols they use, so a shared page cannot assign an example to every family on it.
 * `routeOfPage` parses routes.ts by regex like lib/preview-routes.mjs — keep the formats.
 */

const routeOfPage = (() => {
  const routes = readFileSync('src/preview/routes.ts', 'utf8')
  const fileOf = new Map()
  for (const m of routes.matchAll(/import\s*\{\s*(\w+)\s*\}\s*from\s*"\.\/pages\/([\w-]+)"/g)) {
    fileOf.set(m[1], `${m[2]}.tsx`)
  }
  const out = new Map()
  for (const m of routes.matchAll(/path:\s*"(\/[\w-]*)",\s*label:\s*"([^"]*)",\s*component:\s*(\w+)/g)) {
    const file = fileOf.get(m[3])
    if (file && !out.has(file)) out.set(file, { path: m[1], label: m[2] })
  }
  return out
})()

const recipes = []
for (const file of readdirSync('src/preview/pages').sort()) {
  const text = readFileSync(`src/preview/pages/${file}`, 'utf8')
  const route = routeOfPage.get(file)
  if (!route) continue
  for (const block of text.matchAll(
    /<Example\b([\s\S]*?)code=\{`([\s\S]*?)`\}/g,
  )) {
    const attrs = block[1]
    const id = attrs.match(/\bid="([^"]+)"/)?.[1]
    const title = attrs.match(/\btitle="([^"]+)"/)?.[1]
    if (!id || !title) continue
    const code = block[2].replace(/\\`/g, '`').replace(/\\\$\{/g, '${').replace(/(?<!\\)\\n/g, '\n')
    const usedFamilies = recipeFamilies(code, text, records)
    /* The page's own exports, and a merged page's further families (`alsoImports`). */
    const claimed = [...text.matchAll(/exports=\{\[([\s\S]*?)\]\}|exports:\s*\[([\s\S]*?)\]/g)].flatMap((match) => [...(match[1] ?? match[2]).matchAll(/"([A-Za-z0-9]+)"/g)].map((symbol) => symbol[1]))
    const documented = records.filter((record) => claimed.some((symbol) => record.symbols.includes(symbol)))
    const owners = usedFamilies.filter((id) => documented.some((record) => record.id === id))
    const families = owners.length ? owners : usedFamilies
    const family = records.find((record) => families.includes(record.id) && record.documentation?.includes(`(${route.path})`))
      ?? records.find((record) => families.includes(record.id)) ?? null
    recipes.push({
      id,
      title,
      route: route.path,
      page: route.label,
      family: family?.id ?? null,
      families,
      supportingFamilies: usedFamilies.filter((id) => !families.includes(id)),
      import: family?.import ?? null,
      css: family?.css ?? null,
      code,
    })
  }
}

/*
 * Every preview route and recipe attributed to a family, not just its one
 * `documentationRoute`: the finder searches all of them.
 */
const enrichedRecords = records.map((record) => {
  const familyRecipes = recipes.filter((recipe) => recipe.families.includes(record.id))
  const previews = [
    ...new Map(
      familyRecipes.map((recipe) => [
        `${recipe.route}\u0000${recipe.page}`,
        { route: recipe.route, page: recipe.page },
      ]),
    ).values(),
  ]
  return {
    ...record,
    componentGuidance: record.components.map((symbol) => ({
      symbol,
      publicImport: record.import,
      cssImport: record.css,
      apiDoc: `${record.apiDoc}#${symbol.toLowerCase()}`,
      description: documentedAPI[record.entrypoint]?.[symbol]?.documentation?.description ?? '',
      guidanceSource: guidance[record.id]?.[symbol] ? 'component' : 'family',
      chooseWhen: record.chooseWhen,
      avoidWhen: record.avoidWhen,
      capabilities: [],
      alternatives: [],
      composition: 'Start with props; inspect the public declarations for supported parts and callbacks.',
      ...guidance[record.id]?.[symbol],
    })),
    previews,
    recipes: familyRecipes.map(({ id, title, route, page }) => ({ id, title, route, page })),
  }
})

/* ── component-index.json ────────────────────────────────────────────────────────── */
writeIfChanged(
  `${OUT}/component-index.json`,
  `${JSON.stringify(
    {
      note:
        'Generated by scripts/gen-consumer-docs.mjs. The machine surface: agent skills and ' +
        'component finders read this, not the prose. Every attributed live preview and recipe ' +
        'is indexed under its family.',
      schemaVersion: 2,
      packageVersion: pkg.version,
      package: name,
      profiles: ['general', 'admin'],
      families: enrichedRecords,
    },
    null,
    2,
  )}\n`,
)

/* ── components/*.md — one progressively disclosed API reference per family ─────── */
const COMPONENTS_OUT = `${OUT}/components`
rmSync(COMPONENTS_OUT, { recursive: true, force: true })
mkdirSync(COMPONENTS_OUT, { recursive: true })

const componentLines = [
  HEADER('gen-consumer-docs.mjs') + '# Component-family API',
  '',
  'Open one family at a time. Each reference is generated from the public declaration',
  'snapshot, the architecture manifest, selection guidance, and the live preview recipes.',
  '',
  '| family | layer | profile | reference |',
  '| --- | --- | --- | --- |',
]

for (const record of records) {
  componentLines.push(
    `| \`${record.id}\` | ${record.layer} | ${record.profile} | [API](./${apiSlug(record.id)}.md) |`,
  )

  const declarations = documentedAPI[record.entrypoint] ?? {}
  const applicableRecipes = recipes.filter((recipe) => recipe.families.includes(record.id))
  const lines = [
    HEADER('gen-consumer-docs.mjs') + `# \`${record.id}\``,
    '',
    record.chooseWhen ?? 'Use this family when its public vocabulary matches the interface you are building.',
    '',
    '## Selection',
    '',
    `- **Use when:** ${record.chooseWhen ?? 'the family vocabulary matches the task.'}`,
    `- **Avoid when:** ${record.avoidWhen ?? 'a smaller family expresses the job.'}`,
    `- **Consider instead:** ${record.alternatives?.length ? record.alternatives.map((id) => `\`${id}\``).join(', ') : '—'}`,
    `- **Stability:** ${record.status}.`,
    '',
    '## Import',
    '',
    '```tsx fragment — import-only example',
    `import { ${record.components[0] ?? record.symbols[0]} } from "${record.import}"`,
    ...(record.css ? [`import "${record.css}"`] : []),
    /*
     * A family always used with another it does not import (a menubar's menus ARE dropdown
     * menus) names it in `composeWith` (architecture/selection.json).
     */
    ...(record.composeWith ?? []).flatMap((id) => {
      const partner = records.find((candidate) => candidate.id === id)
      return [
        `import { ${partner.components[0] ?? partner.symbols[0]} } from "${partner.import}"`,
        ...(partner.css ? [`import "${partner.css}"`] : []),
      ]
    }),
    '```',
    '',
  ]

  if (record.optionalPeers.length) {
    lines.push(
      '## Optional peers',
      '',
      'Install these only when importing this family:',
      '',
      '```bash',
      `npm install ${record.optionalPeers.join(' ')}`,
      '```',
      '',
    )
  }

  lines.push(
    '## Composition',
    '',
    record.dependsOnFamilies.length
      ? `This family composes ${record.dependsOnFamilies.map((id) => `\`${id}\``).join(', ')}.`
      : 'This family has no component-family dependencies.',
    ...(record.composeWith?.length
      ? ['', `It is used together with ${record.composeWith.map((id) => `\`${id}\``).join(', ')}: import that family and its stylesheet too.`]
      : []),
    '',
    'Application policy—routing, fetching, persistence, permissions, and translation—stays',
    'outside the package and arrives through the public props, callbacks, slots, or accessors below.',
    '',
    '## Public declarations',
    '',
  )

  for (const [symbol, declaration] of Object.entries(declarations).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`### \`${symbol}\``, '', `Kind: ${declaration.kind}.`, '')
    /* The declaration's own `@deprecated` goes first, before the description sells it. */
    const deprecated = declaration.documentation?.tags?.find((tag) => tag.name === 'deprecated')
    if (deprecated) lines.push(`> **Deprecated.** ${deprecated.text || 'Do not use in new code.'}`, '')
    const description = declaration.documentation?.description
    if (description) lines.push(description.replace(/```(tsx?|jsx?)\s*\n/g, '```$1 fragment — declaration JSDoc excerpt\n'), '')
    const choice = guidance[record.id]?.[symbol]
    if (choice) lines.push(`**Use when:** ${choice.chooseWhen}`, '', `**Avoid when:** ${choice.avoidWhen}`, '', `**Compose:** ${choice.composition}`, '', `**Capabilities:** ${choice.capabilities.join('; ')}.`, '', `**Alternatives:** ${choice.alternatives.join(', ') || '—'}.`, '')
    if (declaration.extends?.length) {
      lines.push(`Extends: ${declaration.extends.map((type) => `\`${type}\``).join(', ')}.`, '')
    }
    if (declaration.signature) {
      lines.push('```text', declaration.signature, '```', '')
    }
    if (declaration.kind === 'interface') {
      const members = Object.entries(declaration.members ?? {})
      if (!members.length) {
        lines.push('No own members are present in the normalized public snapshot.', '')
      } else {
        lines.push('| member | required | type | description / documented default |', '| --- | :-: | --- | --- |')
        for (const [member, detail] of members) {
          lines.push(
            `| \`${member}\` | ${detail.optional ? 'no' : 'yes'} | \`${detail.type.replaceAll('|', '\\|')}\` | ${[declaration.memberDocumentation?.[member]?.description, ...(declaration.memberDocumentation?.[member]?.tags ?? []).map((tag) => `@${tag.name} ${tag.text}`)].filter(Boolean).join(' ').replaceAll('|', '\\|').replaceAll('\n', '<br>')} |`,
          )
        }
        lines.push('')
      }
    }
  }

  lines.push('## Preview recipes', '')
  if (!applicableRecipes.length) {
    lines.push(
      'No dedicated recipe is currently attributed to this family. Use the public declarations',
      'above and the composition guide; this absence is explicit and verification-visible.',
      '',
    )
  } else {
    lines.push(`Preview route: ${applicableRecipes[0].page} — \`${applicableRecipes[0].route}\``, '')
    for (const recipe of applicableRecipes) {
      lines.push(
        `### ${recipe.title}`,
        '',
        '```tsx fragment — excerpt from the live preview; surrounding values are supplied by the application',
        recipe.code.trim(),
        '```',
        '',
      )
    }
  }

  writeIfChanged(`${COMPONENTS_OUT}/${apiSlug(record.id)}.md`, lines.join('\n'))
}

writeIfChanged(`${COMPONENTS_OUT}/INDEX.md`, componentLines.join('\n'))

writeIfChanged(
  `${OUT}/recipes.json`,
  `${JSON.stringify(
    {
      note:
        "Generated by scripts/gen-consumer-docs.mjs from the preview pages' own code blocks — " +
        'the same snippets the human documentation renders. Each names every public family ' +
        'represented on its page; cross-cutting token lessons intentionally name none.',
      recipes,
    },
    null,
    2,
  )}\n`,
)

/* ── build/recipes.md — the Build audience's human surface ───────────────────────── */
const byFamily = new Map()
for (const recipe of recipes) {
  const key = recipe.family ?? '(no family)'
  if (!byFamily.has(key)) byFamily.set(key, [])
  byFamily.get(key).push(recipe)
}
const recipeLines = [
  HEADER('gen-consumer-docs.mjs') + '# Recipes',
  '',
  `${recipes.length} adaptable live-preview snippets, taken from the pages that render them —`,
  'so a recipe here and the example on the page cannot drift apart. Excerpts may depend on',
  'surrounding values supplied by the application. Each section names the exact',
  'import and stylesheet for the family.',
  '',
  '**What the application still owns:** data fetching, routing, persistence, translation and',
  'domain state. Every snippet below assumes those arrive as props, callbacks or accessors.',
  '',
]
for (const [family, list] of [...byFamily].sort()) {
  const first = list[0]
  recipeLines.push(`## ${family}`, '')
  if (first.import) {
    recipeLines.push('```tsx', `import { … } from "${first.import}"`)
    if (first.css) recipeLines.push(`import "${first.css}"`)
    recipeLines.push('```', '')
  }
  recipeLines.push(`Preview route: ${first.page} — \`${first.route}\``, '')
  for (const recipe of list) {
    recipeLines.push(`### ${recipe.title}`, '', '```tsx', recipe.code.trim(), '```', '')
  }
}
mkdirSync('docs/build', { recursive: true })
writeIfChanged('docs/build/recipes.md', recipeLines.join('\n'))

console.log(
  `consumer docs: ${records.length} families, ${symbolRows.length} symbol exports, ` +
    `${records.filter((r) => r.documentation).length} with a documentation route, ` +
    `${recipes.length} recipes`,
)
