/*
 * Writes the consumer catalogue under docs/generated/ from the manifest, the barrels, the
 * built declarations, architecture/{selection,component-guidance}.json and preview pages:
 * imports.md, public-api.md, profiles.md, component-index.json (read by agents and finders),
 * recipes.json, components/*.md, plus docs/build/recipes.md. Prose should link here rather
 * than restate; `verify docs-freshness` fails stale output.
 */
import { apiExportsFor } from './lib/api-exports.mjs'
import { typesFor } from './lib/export-targets.mjs'
import { recipeFamilies, validateGuidance } from './lib/component-discovery.mjs'
import { mkdirSync, readdirSync, readFileSync, rmSync } from 'node:fs'
import ts from 'typescript'
import { writeIfChanged } from './lib/write-if-changed.mjs'
import { readManifest } from './lib/read-architecture-manifest.mjs'
import { publicComponents, publicSymbols } from './lib/public-symbols.mjs'
import { runtimeNames } from './lib/preview-pages.mjs'
import { tierLabel, tierOfLayer } from './lib/tiers.mjs'

/* Hand-authored selection guidance, one entry per family. */
const selection = JSON.parse(readFileSync('architecture/selection.json', 'utf8')).families

const manifest = readManifest()
const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
const builtEntries = Object.entries(pkg.exports).map(([key, target]) => [key, typesFor(target)]).filter(([, file]) => file)
const builtAPI = apiExportsFor(builtEntries.map(([, file]) => file), { documentation: true })
const documentedAPI = Object.fromEntries(builtEntries.map(([key, file]) => [key, Object.fromEntries(builtAPI(file.replace(/^\.\//, '')))]))
const guidance = JSON.parse(readFileSync('architecture/component-guidance.json', 'utf8')).components
const name = pkg.name
const OUT = 'docs/generated'
mkdirSync(OUT, { recursive: true })

const HEADER = (script) => `<!-- GENERATED by scripts/${script} — do not edit. -->\n\n`
const apiSlug = (id) => id.replaceAll('/', '--')

const records = manifest.families
  .filter((family) => family.id !== 'index')
  .map((family) => {
    const symbols = publicSymbols(family.source)
    const components = publicComponents(family.source)
    return {
      id: family.id,
      profile: family.profile,
      tier: tierOfLayer(family.layer),
      entrypoint: family.export,
      import: `${name}${family.export.slice(1)}`,
      css: family.cssExport ? `${name}${family.cssExport.slice(1)}` : null,
      optionalPeers: family.optionalPeers,
      dependsOn: family.dependsOnFamilies,
      documentation: family.documentationRoute
        ? `${family.documentationRoute.label} (${family.documentationRoute.path})`
        : null,
      status: family.status,
      symbols,
      components,
      apiDoc: `components/${apiSlug(family.id)}.md`,
      ...(selection[family.id] ?? {}),
    }
  })
  .sort((a, b) => a.id.localeCompare(b.id))

const guidanceErrors = validateGuidance(guidance, records)
if (guidanceErrors.length) throw new Error(guidanceErrors.join('\n'))

