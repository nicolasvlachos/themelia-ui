/* ── recipes.json ────────────────────────────────────────────────────────────────── */
/*
 * Recipes are the preview pages' examples — an `<Example example="page/id">` reads its file in
 * src/preview/examples, an `<Example code={…}>` its string — attributed by the public symbols
 * they use, so a shared page cannot assign an example to every family on it.
 */

/* page file → its route and the names its import lines document, from the preview's page table */
const routeOfPage = new Map(
  JSON.parse(readFileSync('src/preview/routes.json', 'utf8')).routes.map((row) => [
    `${row.page}.tsx`,
    { path: row.path, label: row.label, claimed: runtimeNames((row.imports ?? []).flatMap((entry) => entry.names)) },
  ]),
)

/** The page's `<Example>` elements, parsed rather than matched: `title`, `id`, `example` and `code`. */
function examplesIn(file, text) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const attribute = (tag, name) => {
    const found = tag.attributes.properties.find((property) => ts.isJsxAttribute(property) && property.name.getText(source) === name)
    const value = found?.initializer
    if (!value) return undefined
    if (ts.isStringLiteral(value)) return value.text
    const expression = ts.isJsxExpression(value) ? value.expression : undefined
    if (expression && (ts.isStringLiteral(expression) || ts.isNoSubstitutionTemplateLiteral(expression))) return expression.text
    if (expression && ts.isTemplateExpression(expression)) return expression.getText(source).slice(1, -1)
    return undefined
  }
  const found = []
  const visit = (node) => {
    const tag = ts.isJsxSelfClosingElement(node) ? node : ts.isJsxElement(node) ? node.openingElement : undefined
    if (tag && tag.tagName.getText(source) === 'Example') {
      found.push({ title: attribute(tag, 'title'), id: attribute(tag, 'id'), example: attribute(tag, 'example'), code: attribute(tag, 'code') })
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return found
}

const recipes = []
for (const file of readdirSync('src/preview/pages').sort()) {
  const text = readFileSync(`src/preview/pages/${file}`, 'utf8')
  const route = routeOfPage.get(file)
  if (!route) continue
  for (const entry of examplesIn(file, text)) {
    const id = entry.example ? entry.example.split('/').pop() : entry.id
    const code = entry.example ? readFileSync(`src/preview/examples/${entry.example}.tsx`, 'utf8').trimEnd() : entry.code
    const title = entry.title
    if (!id || !title || !code) continue
    const usedFamilies = recipeFamilies(code, text, records)
    const documented = records.filter((record) => route.claimed.some((symbol) => record.symbols.includes(symbol)))
    const owners = usedFamilies.filter((id) => documented.some((record) => record.id === id))
    const families = owners.length ? owners : usedFamilies
    const family = records.find((record) => families.includes(record.id) && record.documentation?.includes(`(${route.path})`))
      ?? records.find((record) => families.includes(record.id)) ?? null
    recipes.push({
      id,
      title,
      route: route.path,
      page: route.label,
      module: family?.id ?? null,
      modules: families,
      supportingModules: usedFamilies.filter((id) => !families.includes(id)),
      import: family?.import ?? null,
      css: family?.css ?? null,
      code,
    })
  }
}

/*
 * Every preview route and recipe attributed to a family, not just its one
 * `documentationRoute`: the finder searches all of them.
 */
const enrichedRecords = records.map((record) => {
  const familyRecipes = recipes.filter((recipe) => recipe.modules.includes(record.id))
  const previews = [
    ...new Map(
      familyRecipes.map((recipe) => [
        `${recipe.route}\u0000${recipe.page}`,
        { route: recipe.route, page: recipe.page },
      ]),
    ).values(),
  ]
  return {
    ...record,
    componentGuidance: record.components.map((symbol) => ({
      symbol,
      publicImport: record.import,
      cssImport: record.css,
      apiDoc: `${record.apiDoc}#${symbol.toLowerCase()}`,
      description: documentedAPI[record.entrypoint]?.[symbol]?.documentation?.description ?? '',
      guidanceSource: guidance[record.id]?.[symbol] ? 'component' : 'module',
      chooseWhen: record.chooseWhen,
      avoidWhen: record.avoidWhen,
      capabilities: [],
      alternatives: [],
      composition: 'Start with props; inspect the public declarations for supported parts and callbacks.',
      ...guidance[record.id]?.[symbol],
    })),
    previews,
    recipes: familyRecipes.map(({ id, title, route, page }) => ({ id, title, route, page })),
  }
})

