/* The inverse table: optional peer → families that reach it. */
const byPeer = new Map()
for (const record of records) {
  for (const peer of record.optionalPeers) {
    if (!byPeer.has(peer)) byPeer.set(peer, [])
    byPeer.get(peer).push(record.id)
  }
}
importLines.push(
  `## Optional peers — ${byPeer.size} of them`,
  '',
  'Each is reachable only from the modules below, so a consumer who never imports one never',
  'resolves it. Release verification rejects a module that reaches an undeclared peer.',
  '',
  '| peer | reachable from |',
  '| --- | --- |',
)
for (const [peer, families] of [...byPeer].sort()) {
  importLines.push(`| \`${peer}\` | ${families.map((f) => `\`${f}\``).join(', ')} |`)
}
importLines.push('')

writeIfChanged(`${OUT}/imports.md`, importLines.join('\n'))

