/*
 * Writes architecture/api-snapshot.json: every declaration each subpath's `types` target
 * exports (what consumers resolve, not the source), with signatures normalised by
 * lib/api-signatures.mjs. verify-api-snapshot.mjs diffs the build against it.
 */
import { readFileSync, writeFileSync } from 'node:fs'

import { apiExportsFor } from './lib/api-exports.mjs'
import { typesFor as typesForEntry } from './lib/export-targets.mjs'

const OUT = 'architecture/api-snapshot.json'

const pkg = JSON.parse(readFileSync('package.json', 'utf8'))

const entrypoints = Object.entries(pkg.exports)
  .map(([subpath, target]) => [subpath, typesForEntry(target)])
  .filter(([, types]) => types)
const declarations = apiExportsFor(entrypoints.map(([, file]) => file))

const surface = {}
for (const [subpath, types] of entrypoints) {
  const entries = declarations(types.replace(/^\.\//, ''))
  const merged = new Map()
  for (const [name, record] of entries) merged.set(name, record)
  surface[subpath] = Object.fromEntries([...merged].sort(([a], [b]) => a.localeCompare(b)))
}

writeFileSync(
  OUT,
  `${JSON.stringify(
    {
      note:
        'The public surface of every exact entrypoint, by name and normalised signature. Generated by ' +
        'scripts/gen-api-snapshot.mjs from the `types` target each subpath resolves to. ' +
        'A removed name, a removed member, or an optional member made required is breaking; ' +
        'an added name or an added optional member is additive. ' +
        'verify api-snapshot fails on removals until this file is regenerated deliberately.',
      version: pkg.version,
      entrypoints: Object.fromEntries(Object.entries(surface).sort(([a], [b]) => a.localeCompare(b))),
    },
    null,
    2,
  )}\n`,
)

const names = Object.values(surface).reduce((n, e) => n + Object.keys(e).length, 0)
console.log(`api snapshot: ${Object.keys(surface).length} entrypoints, ${names} declarations`)
