/**
 * Emits a `.module.css.d.ts` beside every `.module.css` under src/, listing its exact
 * class keys so a typo in `styles.x` is a compile error rather than `undefined`.
 * Names are camel-cased to match `localsConvention: "camelCaseOnly"` in vite.shared.ts.
 */
import {
  readFileSync,
  writeFileSync,
  readdirSync,
  statSync,
  renameSync,
  unlinkSync,
} from 'node:fs'
import { join } from 'node:path'

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const p = join(dir, entry)
    if (statSync(p).isDirectory()) out.push(...walk(p))
    else if (entry.endsWith('.module.css')) out.push(p)
  }
  return out
}

/**
 * Must match the bundler's camel-casing exactly, or the types lie: lodash `camelCase`
 * breaks words at digit/letter boundaries, so `.size2xl` is `size2Xl`, not `size2xl`.
 */
const camel = (name) =>
	name
		.replace(/([a-zA-Z])([0-9])/g, "$1 $2")
		.replace(/([0-9])([a-zA-Z])/g, "$1 $2")
		.split(/[^a-zA-Z0-9]+/)
		.filter(Boolean)
		.map((word, index) =>
			index === 0
				? word.charAt(0).toLowerCase() + word.slice(1)
				: word.charAt(0).toUpperCase() + word.slice(1),
		)
		.join("")

function readIfExists(path) {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

/*
 * Write via a temp file so no reader sees a half-written file; Windows can refuse the
 * rename over an open file, so fall back to a direct write.
 */
function writeAtomic(path, data) {
  const tmp = `${path}.${process.pid}.tmp`
  writeFileSync(tmp, data)
  try {
    renameSync(tmp, path)
  } catch {
    try {
      unlinkSync(tmp)
    } catch {}
    writeFileSync(path, data)
  }
}

let count = 0
let unchanged = 0
for (const file of walk('src')) {
  const css = readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')
  const names = new Set()
  // :global(...) classes are not exported locals.
  for (const m of css.replace(/:global\([^)]*\)/g, '').matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
    names.add(camel(m[1]))
  }
  const sorted = [...names].sort()
  const body = sorted.map((n) => `\treadonly ${n}: string`).join('\n')
  const out = `${file}.d.ts`
  const next =
    `// GENERATED by scripts/gen-css-types.mjs — do not edit.\n` +
    `declare const styles: {\n${body}\n}\nexport default styles\n`

  // Skip unchanged files: needless mtime bumps retrigger tsc/Vite watchers and race readers (EPERM).
  if (readIfExists(out) === next) {
    unchanged++
    continue
  }
  writeAtomic(out, next)
  count++
}
console.log(
  `generated ${count} CSS module declaration file(s); ${unchanged} already current`,
)
